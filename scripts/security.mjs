// Shared response headers for the local preview server and the Netlify release.
// Do not add third-party form, analytics, or iframe hosts to this policy without review.
export const securityHeaders = Object.freeze({
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'X-Frame-Options': 'DENY',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=()',
  'Content-Security-Policy': "default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; frame-src 'none'; script-src 'self'; style-src 'self'; style-src-attr 'unsafe-inline'; img-src 'self' https://images.unsplash.com data:; font-src 'self'; connect-src 'self'; form-action 'self'"
});
export const willPageHeaders = Object.freeze({
  'Cache-Control': 'no-store, max-age=0'
});
export function netlifyHeaderFile() {
  const common = Object.entries(securityHeaders).map(([key,value])=>`  ${key}: ${value}`).join('\n');
  const sensitive = Object.entries(willPageHeaders).map(([key,value])=>`  ${key}: ${value}`).join('\n');
  return `# Generated by scripts/build.mjs from scripts/security.mjs.\n/*\n${common}\n/will-drafting.html\n${sensitive}\n`;
}
